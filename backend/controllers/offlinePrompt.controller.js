/**
 * @desc    Download JSON file
 * @route   GET /api/offline-prompts/:id/download
 * @access  Private (Admin)
 */
exports.downloadPromptFile = async (req, res, next) => {
  try {
    const { id } = req.params;

    const result = await offlinePromptService.getPromptById(id);
    const prompt = result.prompt;

    // Record download
    await prompt.recordDownload();

    // Send file for download
    res.download(prompt.filePath, prompt.fileName, (err) => {
      if (err) {
        logger.error('File download error:', err);
        if (!res.headersSent) {
          res.status(404).json({
            success: false,
            message: 'File not found'
          });
        }
      }
    });
  } catch (error) {
    logger.error('Download prompt file error:', error);
    next(error);
  }
};

/**
 * @desc    Get unique filter values
 * @route   GET /api/offline-prompts/filters/values
 * @access  Private (Admin)
 */
exports.getFilterValues = async (req, res, next) => {
  try {
    const QuestionOfflinePrompt = require('../models/QuestionOfflinePrompt.model');

    const [grades, subjects, chapters, difficulties, statuses] = await Promise.all([
      QuestionOfflinePrompt.distinct('grade'),
      QuestionOfflinePrompt.distinct('subject'),
      QuestionOfflinePrompt.distinct('chapterName'),
      QuestionOfflinePrompt.distinct('difficultyLevel'),
      QuestionOfflinePrompt.distinct('status')
    ]);

    res.json({
      success: true,
      filters: {
        grades: grades.sort(),
        subjects: subjects.sort(),
        chapters: chapters.sort(),
        difficulties: difficulties,
        statuses: statuses
      }
    });
  } catch (error) {
    logger.error('Get filter values error:', error);
    next(error);
  }
};
