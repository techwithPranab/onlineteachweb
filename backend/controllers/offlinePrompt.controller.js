const offlinePromptService = require('../services/offlinePromptService');
const logger = require('../utils/logger');

/**
 * @desc    Generate offline prompt
 * @route   POST /api/offline-prompts/generate
 * @access  Private (Admin)
 */
exports.generateOfflinePrompt = async (req, res, next) => {
  try {
    const {
      courseId,
      chapterId,
      grade,
      subject,
      chapterName,
      topic,
      difficultyLevel,
      questionType,
      questionsCount,
      sources,
      includeExplanations,
      includeHints,
      notes
    } = req.body;

    // Validate required fields
    if (!courseId || !grade || !subject || !chapterName || !topic || !difficultyLevel || !questionType) {
      return res.status(400).json({
        success: false,
        message: 'Missing required fields'
      });
    }

    // Generate offline prompt
    const result = await offlinePromptService.generateOfflinePrompt({
      courseId,
      chapterId,
      grade,
      subject,
      chapterName,
      topic,
      difficultyLevel,
      questionType,
      questionsCount: questionsCount || 5,
      sources: sources || ['syllabus'],
      includeExplanations: includeExplanations !== false,
      includeHints: includeHints === true,
      notes,
      saveToFile: false
    }, req.user._id);

    logger.info(`Offline prompt generated by user ${req.user._id}`);

    res.status(201).json(result);
  } catch (error) {
    logger.error('Generate offline prompt error:', error);
    next(error);
  }
};

/**
 * @desc    Get all offline prompts with pagination and filters
 * @route   GET /api/offline-prompts
 * @access  Private (Admin)
 */
exports.getAllPrompts = async (req, res, next) => {
  try {
    const {
      page = 1,
      limit = 20,
      courseId,
      grade,
      subject,
      chapterName,
      topic,
      difficultyLevel,
      status,
      generatedBy
    } = req.query;

    const filters = {};
    if (courseId) filters.courseId = courseId;
    if (grade) filters.grade = grade;
    if (subject) filters.subject = subject;
    if (chapterName) filters.chapterName = chapterName;
    if (topic) filters.topic = topic;
    if (difficultyLevel) filters.difficultyLevel = difficultyLevel;
    if (status) filters.status = status;
    if (generatedBy) filters.generatedBy = generatedBy;

    const result = await offlinePromptService.getPrompts(
      filters,
      parseInt(page),
      parseInt(limit)
    );

    res.json(result);
  } catch (error) {
    logger.error('Get prompts error:', error);
    next(error);
  }
};

/**
 * @desc    Get single offline prompt by ID
 * @route   GET /api/offline-prompts/:id
 * @access  Private (Admin)
 */
exports.getPromptById = async (req, res, next) => {
  try {
    const { id } = req.params;

    const result = await offlinePromptService.getPromptById(id);

    res.json(result);
  } catch (error) {
    logger.error('Get prompt by ID error:', error);
    if (error.message === 'Prompt not found') {
      return res.status(404).json({
        success: false,
        message: 'Prompt not found'
      });
    }
    next(error);
  }
};

/**
 * @desc    Delete offline prompt
 * @route   DELETE /api/offline-prompts/:id
 * @access  Private (Admin)
 */
exports.deletePrompt = async (req, res, next) => {
  try {
    const { id } = req.params;

    const result = await offlinePromptService.deletePrompt(id);

    logger.info(`Offline prompt ${id} deleted by user ${req.user._id}`);

    res.json(result);
  } catch (error) {
    logger.error('Delete prompt error:', error);
    if (error.message === 'Prompt not found') {
      return res.status(404).json({
        success: false,
        message: 'Prompt not found'
      });
    }
    next(error);
  }
};

